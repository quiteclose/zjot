#!/usr/bin/env python3
"""Writes test/grid.test: every block family bare, under a block attribute, inside a block
quote and inside a list item, each in HTML and in `ap` (positions), plus the shapes that make
a block wait for a later one (a reference defined after use, an implicit reference before and
after its heading, two headings with one text, footnotes defined before and after use, a
definition redefined). Every expectation is djot.js 0.3.2's, through `npx` and djot2ast.py,
so the file is regenerated whole:

    python3 test/tools/gen-grid.py            (after `zig build`, to compare)

Where zjot's output differs, the difference is printed and the exit code is 1; the
expectation written is still djot.js's, so the suite shows the divergence until it is
fixed or the case is taken out here with a note. Headings carry explicit ids: zjot prints
generated ones and djot.js does not (see the zjot.test header). Local only: CI has no npm."""
import os, subprocess, sys

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(root)
env = dict(os.environ, npm_config_loglevel='error')

# (name, source, positions): a family whose AST text form differs from djot.js's by a
# documented difference (a raw block's format, a reference link's resolved destination; see
# the zjot.test header) is compared in HTML only.
families = [
    ('paragraph', 'para *em* text', True),
    ('heading', '{#h}\n## Head', True),
    ('thematic break', '***', True),
    ('code block', '```\ncode\n```', True),
    ('raw block', '```=html\n<b>x</b>\n```', False),
    ('block quote', '> quoted', True),
    ('bullet list', '- one\n- two', True),
    ('ordered list', '1. one\n2. two', True),
    ('task list', '- [x] done\n- [ ] todo', True),
    ('definition list', ': term\n\n  def', True),
    ('table', '| a | b |\n|---|--:|\n| 1 | 2 |\n^ cap', True),
    ('div', '::: cls\ninner\n:::', True),
    ('footnote', 'text[^n]\n\n[^n]: note', True),
    ('reference link', '[t][r]\n\n[r]: /u', False),
]

def bare(s): return s
def attributed(s): return '{.x}\n' + s
def quoted(s): return '\n'.join(('> ' + l) if l else '>' for l in s.split('\n'))
def in_item(s):
    lines = s.split('\n')
    return '\n'.join(['- ' + lines[0]] + [('  ' + l) if l else '' for l in lines[1:]])

wrappers = [('bare', bare), ('under a block attribute', attributed), ('in a block quote', quoted), ('in a list item', in_item)]

holds = [
    ('a reference defined after its use', 'See [the doc][d] and [other][o].\n\nMore.\n\n[d]: /doc\n[o]: /other', False),
    ('an implicit reference before its heading', '[Later][]\n\n{#later}\n# Later', False),
    ('an implicit reference after its heading', '{#early}\n# Early\n\n[Early][]', False),
    ('two headings with one text', '{#a}\n# Same\n\n{#b}\n# Same\n\n[Same][]', False),
    ('a footnote defined before its use', '[^a]: first\n\nuse[^a]', True),
    ('a footnote defined after its use', 'use[^b]\n\n[^b]: later', True),
    ('a reference definition redefined', '[r]: /one\n\n[x][r]\n\n[r]: /two', False),
    ('a footnote redefined', '[^n]: one\n\nuse[^n]\n\n[^n]: two', True),
]

def djot_html(src):
    return subprocess.run(['npx', '-y', '@djot/djot@0.3.2'], input=src.encode(), capture_output=True, env=env, check=True).stdout.decode()

def djot_ast(src):
    return subprocess.run(['python3', 'test/tools/djot2ast.py', '-p'], input=src.encode(), capture_output=True, env=env, check=True).stdout.decode()

zjot = 'zig-out/bin/zjot' if os.path.exists('zig-out/bin/zjot') else None

def zjot_out(src, ast):
    args = [zjot] + (['--ast', '--sourcepos'] if ast else [])
    return subprocess.run(args, input=src.encode(), capture_output=True, check=True).stdout.decode()

out = ['''Generated by test/tools/gen-grid.py from djot.js 0.3.2: every block family bare, under a
block attribute, in a block quote and in a list item, in HTML and with positions, and the
shapes that make a block wait for a later one. Regenerate it whole; do not edit by hand.
''']
divergent = 0
total = 0

def case(title, src, ast):
    global divergent, total
    total += 1
    # The runner feeds a case's lines each with a newline, so the tools see the same input.
    expected = djot_ast(src + '\n') if ast else djot_html(src + '\n')
    if zjot:
        got = zjot_out(src + '\n', ast)
        if got != expected:
            divergent += 1
            mode = 'ap' if ast else 'html'
            print(f'--- divergence: {title} ({mode})\n{src}\n--- djot.js\n{expected}--- zjot\n{got}', file=sys.stderr)
    fence = '```` ap' if ast else '````'
    out.append(f'\n{title}.\n{fence}\n{src}\n.\n{expected}````\n')

for fname, snippet, positions in families:
    for wname, wrap in wrappers:
        src = wrap(snippet)
        for ast in ((False, True) if positions else (False,)):
            case(f'A {fname} {wname}', src, ast)
for hname, src, positions in holds:
    for ast in ((False, True) if positions else (False,)):
        case(f'Waiting: {hname}', src, ast)

with open('test/grid.test', 'w', encoding='utf-8') as f:
    f.write(''.join(out))
print(f'test/grid.test: {total} cases, {divergent} divergent' + ('' if zjot else ' (zjot not built: nothing compared)'))
sys.exit(1 if divergent else 0)
